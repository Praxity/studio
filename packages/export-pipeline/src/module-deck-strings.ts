import { interpolate } from "@praxity/shared-blocks/i18n/interpolate";
import type { DeckPage } from "./module-deck";

export function nextModuleLabel(
	locale: string,
	destination?: Pick<DeckPage, "lessonTitle" | "title">,
): string {
	const t = deckStrings(locale);
	return destination
		? interpolate(t.nextModuleTo, { title: destination.lessonTitle ?? destination.title })
		: t.backToCourse;
}

